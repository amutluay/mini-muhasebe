import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = ['accounting.js', 'csv.js', 'storage.js', 'templates.js', 'journal-print.js', 'voucher-navigation.js', 'bulk-print.js', 'app.js'];
const csv = await readFile(resolve(root, 'data/hesap-plani.csv'), 'utf8');
const parts = [];

for (const name of modules) {
  let source = await readFile(resolve(root, name), 'utf8');
  source = source.replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];\s*/gm, '');
  source = source.replace(/\bexport\s+(?=(?:async\s+)?(?:const|function)\b)/g, '');
  if (/^\s*(?:import|export)\b/m.test(source)) throw new Error(`${name} modülü birleştirilemedi.`);
  parts.push(`// ${name}\n${source}`);
}

const output = `// Generated by npm run build. Edit source modules, then rebuild.\n(async () => {\nconst DEFAULT_ACCOUNT_CSV = ${JSON.stringify(csv)};\n${parts.join('\n\n')}\n})().catch(error => {\n  const app = document.querySelector('#app');\n  if (app) app.textContent = 'Uygulama açılamadı: ' + error.message;\n});\n`;
const target = resolve(root, 'standalone.js');
if (process.argv.includes('--check')) {
  const existing = await readFile(target, 'utf8');
  if (existing !== output) throw new Error('standalone.js güncel değil. npm run build çalıştırın.');
} else {
  await writeFile(target, output);
  console.log('standalone.js oluşturuldu.');
}
